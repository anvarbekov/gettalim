export const DICT: Record<Lang, Dict> = { uz, ru, en };
export type TKey = keyof Dict;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let value: string = DICT[lang][key] ?? DICT.uz[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, String(v));
  }
  return value;
}
