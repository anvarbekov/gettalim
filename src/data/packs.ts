/** Raqamli javobli savol — variantlar avtomatik yaratiladi (yaqin sonlar). */
const num = (id: string, prompt: string, answer: string, extra: Partial<Question> = {}): Question => ({
  id,
  type: "number",
  prompt,
  answer,
  ...extra,
});

/** Variantli savol — birinchi variant to'g'ri, o'yinda aralashtiriladi. */
